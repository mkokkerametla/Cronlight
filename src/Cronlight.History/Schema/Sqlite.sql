-- Cronlight execution history (SQLite). {TABLE} is the history table name,
-- by default the Quartz table prefix + CRONLIGHT_HISTORY, e.g. QRTZ_CRONLIGHT_HISTORY.
-- {NAME} is the same name without a schema and {SCHEMA} the schema with its dot (e.g. "main.") or
-- nothing: SQLite puts the schema on the index name, not on the table it indexes.
CREATE TABLE {TABLE} (
    ID INTEGER PRIMARY KEY AUTOINCREMENT,
    SCHED_NAME TEXT NOT NULL,
    ENTRY_ID TEXT NOT NULL,
    INSTANCE_NAME TEXT NOT NULL,
    JOB_NAME TEXT NOT NULL,
    JOB_GROUP TEXT NOT NULL,
    JOB_TYPE TEXT NULL,
    TRIGGER_NAME TEXT NULL,
    TRIGGER_GROUP TEXT NULL,
    SCHEDULED_TIME BIGINT NULL,
    FIRED_TIME BIGINT NOT NULL,
    FINISHED_TIME BIGINT NULL,
    DURATION_MS BIGINT NULL,
    STATUS TEXT NOT NULL,
    ERROR TEXT NULL,
    REFIRE_COUNT INTEGER NOT NULL
);
CREATE INDEX {SCHEMA}IDX_{NAME}_ID ON {NAME} (SCHED_NAME, ID);
CREATE INDEX {SCHEMA}IDX_{NAME}_JOB ON {NAME} (SCHED_NAME, JOB_GROUP, JOB_NAME, ID);
CREATE INDEX {SCHEMA}IDX_{NAME}_ENTRY ON {NAME} (SCHED_NAME, ENTRY_ID);
CREATE INDEX {SCHEMA}IDX_{NAME}_FIRED ON {NAME} (SCHED_NAME, FIRED_TIME);
