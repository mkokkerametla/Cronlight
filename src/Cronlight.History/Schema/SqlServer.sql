-- Cronlight execution history (SQL Server). {TABLE} is the history table name,
-- by default the Quartz table prefix + CRONLIGHT_HISTORY, e.g. QRTZ_CRONLIGHT_HISTORY.
-- {NAME} is the same name without a schema, used in index names.
CREATE TABLE {TABLE} (
    ID BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    SCHED_NAME NVARCHAR(120) NOT NULL,
    ENTRY_ID NVARCHAR(140) NOT NULL,
    INSTANCE_NAME NVARCHAR(200) NOT NULL,
    JOB_NAME NVARCHAR(150) NOT NULL,
    JOB_GROUP NVARCHAR(150) NOT NULL,
    JOB_TYPE NVARCHAR(250) NULL,
    TRIGGER_NAME NVARCHAR(150) NULL,
    TRIGGER_GROUP NVARCHAR(150) NULL,
    SCHEDULED_TIME BIGINT NULL,
    FIRED_TIME BIGINT NOT NULL,
    FINISHED_TIME BIGINT NULL,
    DURATION_MS BIGINT NULL,
    STATUS NVARCHAR(16) NOT NULL,
    ERROR NVARCHAR(4000) NULL,
    REFIRE_COUNT INT NOT NULL
);
CREATE INDEX IDX_{NAME}_ID ON {TABLE} (SCHED_NAME, ID);
CREATE INDEX IDX_{NAME}_JOB ON {TABLE} (SCHED_NAME, JOB_GROUP, JOB_NAME, ID);
CREATE INDEX IDX_{NAME}_ENTRY ON {TABLE} (SCHED_NAME, ENTRY_ID);
CREATE INDEX IDX_{NAME}_FIRED ON {TABLE} (SCHED_NAME, FIRED_TIME);
CREATE INDEX IDX_{NAME}_STATUS ON {TABLE} (SCHED_NAME, STATUS, ID);
